import { useEffect, useMemo, useRef, useState } from 'react';

/**
 * Renders markup produced by the export renderers directly into the page.
 *
 * Screen and file therefore come from one code path: what the reader sees is
 * what downloads. The only deliberate difference is that the on-screen version
 * omits the mandatory note block (the surrounding FigureFrame shows it instead)
 * and scales to the container width.
 */
export function InlineSvgChart({
  render, ariaLabel, className, minWidth = 420,
}: {
  render: (width: number) => string;
  ariaLabel: string;
  className?: string;
  minWidth?: number;
}) {
  const containerRef = useRef<HTMLDivElement>(null);
  const [width, setWidth] = useState(720);

  useEffect(() => {
    const element = containerRef.current;
    if (!element || typeof ResizeObserver === 'undefined') return;
    const observer = new ResizeObserver((entries) => {
      const next = entries[0]?.contentRect.width;
      if (next && next > 0) setWidth(Math.max(minWidth, Math.floor(next)));
    });
    observer.observe(element);
    return () => observer.disconnect();
  }, [minWidth]);

  const markup = useMemo(() => render(width), [render, width]);

  return (
    <div
      ref={containerRef}
      className={className}
      role="img"
      aria-label={ariaLabel}
      // The markup is generated by this application's own renderers from
      // validated numeric data; no third-party or user HTML reaches it.
      dangerouslySetInnerHTML={{ __html: markup }}
    />
  );
}
