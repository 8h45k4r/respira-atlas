/**
 * Statistical charts are generated by this module for both the screen and the
 * exported file. The React components embed exactly the markup produced here, so
 * a downloaded chart is the chart the reader looked at — there is no second
 * rendering path that could drift from the first.
 */

export interface ChartFrame {
  readonly width: number;
  readonly height: number;
  readonly margin: { top: number; right: number; bottom: number; left: number };
}

interface Scale {
  (value: number): number;
  readonly domain: readonly [number, number];
  readonly range: readonly [number, number];
}

function linearScale(
  domain: readonly [number, number],
  range: readonly [number, number],
): Scale {
  const [d0, d1] = domain;
  const [r0, r1] = range;
  const span = d1 - d0 || 1;
  const scale = ((value: number) => r0 + ((value - d0) / span) * (r1 - r0)) as {
    (value: number): number;
    domain?: readonly [number, number];
    range?: readonly [number, number];
  };
  scale.domain = domain;
  scale.range = range;
  return scale as Scale;
}

/** Axis ticks at human-readable intervals ("nice numbers"). */
export function niceTicks(min: number, max: number, count = 5): number[] {
  if (!Number.isFinite(min) || !Number.isFinite(max) || min === max) return [min];
  const span = max - min;
  const rawStep = span / count;
  const magnitude = 10 ** Math.floor(Math.log10(rawStep));
  const normalised = rawStep / magnitude;
  const step =
    (normalised >= 7.5 ? 10 : normalised >= 3.5 ? 5 : normalised >= 1.5 ? 2 : 1) * magnitude;
  const start = Math.ceil(min / step) * step;
  const ticks: number[] = [];
  for (let value = start; value <= max + step * 1e-9; value += step) {
    ticks.push(Number(value.toFixed(10)));
  }
  return ticks;
}

function domainFor(
  values: readonly number[],
  { padding = 0.08, includeZero = false }: { padding?: number; includeZero?: boolean } = {},
): [number, number] {
  if (values.length === 0) return [0, 1];
  let min = Math.min(...values);
  let max = Math.max(...values);
  if (includeZero) min = Math.min(0, min);
  if (min === max) {
    const nudge = Math.abs(min) * 0.1 || 1;
    return [min - nudge, max + nudge];
  }
  const pad = (max - min) * padding;
  return [min - pad, max + pad];
}

function footer(
  notes: MandatoryNotes | null,
  x: number,
  y: number,
  maxWidth: number,
  size: number,
): { svg: string; height: number } {
  if (!notes) return { svg: '', height: 0 };
  const fragments: string[] = [
    `<line x1="${x}" y1="${round(y)}" x2="${round(x + maxWidth)}" y2="${round(y)}" stroke="#cbd5e1" stroke-width="1" />`,
  ];
  let cursor = y + 10;
  for (const noteLine of mandatoryNoteLines(notes)) {
    const wrapped = paragraph(noteLine, {
      x, y: cursor + size, size, fill: '#475569', maxWidth, lineHeight: size * 1.38,
    });
    fragments.push(wrapped.svg);
    cursor += wrapped.height + 1;
  }
  return { svg: fragments.join('\n'), height: cursor - y + 6 };
}

